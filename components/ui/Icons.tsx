export function ServiceIcon({
  name,
  className,
}: {
  name: "building" | "hardhat" | "blocks";
  className?: string;
}) {
  if (name === "building") return <BuildingIcon className={className} />;
  if (name === "hardhat") return <HardhatIcon className={className} />;
  return <BlocksIcon className={className} />;
}

export function ValueIcon({
  name,
  className,
}: {
  name: "shield" | "trophy" | "handshake" | "clock";
  className?: string;
}) {
  switch (name) {
    case "shield":
      return <ShieldIcon className={className} />;
    case "trophy":
      return <TrophyIcon className={className} />;
    case "handshake":
      return <HandshakeIcon className={className} />;
    case "clock":
      return <ClockIcon className={className} />;
  }
}
